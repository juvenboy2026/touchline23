import Foundation

public struct Configuration: Codable, Equatable, Sendable {
    public var automatic = false
    public var outputAutomatic = true
    public var repository = ""
    /// No built-in default: the stock system interpreter lacks the build
    /// dependencies, and a machine-specific path must not live in shared code.
    /// The environment is discovered next to the selected repository or chosen
    /// by hand, then persisted with the other local settings.
    public var python = ""
    /// Every platform this batch builds, in the order they run. One target is a
    /// batch of one; two targets build one after the other, each with its own
    /// review, task directory and audit.
    public var targets = ["macos"]
    public var mode = "nsp"
    /// Directory builds still consume this exact update: retain it while disabling
    /// its editor. Every mode change is a configuration change and invalidates review.
    public var updateSelectionEnabled: Bool { mode != "directory" }
    public var base = ""
    public var update = ""
    public var keys = ""
    public var output = ""
    public var exefs = ""
    public var romfs = ""
    /// Extracted add-on content: one numeric folder per DLC. The iOS runtime
    /// mounts it (DM_AOC_DIR) and only the directory backend packs it.
    public var aoc = ""
    public var cache = ""
    public var library = ""
    public var shaderAction = "reuse"
    public var jobs = 4
    /// Optional path of a catalog file generated by
    /// `tools/packaging_gui/registry.py --index`. Empty means the supported-games
    /// list is read from `dm/games` in the selected repository; a bundled build
    /// can ship the generated catalog instead, which is why the reader and the
    /// writer share one schema.
    public var gamesIndex = ""

    public init() {}

    private enum Keys: String, CodingKey {
        case automatic, outputAutomatic, repository, python, targets, mode, base, update, keys, output, exefs, romfs, aoc,
             cache, library, shaderAction, jobs, gamesIndex
    }
    /// Settings written before the platform became multi-select stored one
    /// `target`; they are read into a one-entry batch instead of being dropped.
    private enum Legacy: String, CodingKey { case target }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: Keys.self)
        func text(_ key: Keys, _ fallback: String = "") throws -> String {
            try c.decodeIfPresent(String.self, forKey: key) ?? fallback
        }
        automatic = try c.decodeIfPresent(Bool.self, forKey: .automatic) ?? false
        outputAutomatic = try c.decodeIfPresent(Bool.self, forKey: .outputAutomatic) ?? (try text(.output)).isEmpty
        repository = try text(.repository)
        python = try text(.python)
        mode = try text(.mode, "nsp")
        base = try text(.base); update = try text(.update); keys = try text(.keys)
        output = try text(.output); exefs = try text(.exefs); romfs = try text(.romfs)
        aoc = try text(.aoc); cache = try text(.cache); library = try text(.library)
        shaderAction = try text(.shaderAction, "reuse")
        jobs = try c.decodeIfPresent(Int.self, forKey: .jobs) ?? 4
        gamesIndex = try text(.gamesIndex)
        if let list = try c.decodeIfPresent([String].self, forKey: .targets) {
            targets = Configuration.normalized(list)
        } else {
            let legacy = try decoder.container(keyedBy: Legacy.self)
            targets = Configuration.normalized([try legacy.decodeIfPresent(String.self, forKey: .target) ?? "macos"])
        }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: Keys.self)
        try c.encode(automatic, forKey: .automatic)
        try c.encode(outputAutomatic, forKey: .outputAutomatic)
        try c.encode(repository, forKey: .repository)
        try c.encode(python, forKey: .python)
        try c.encode(targets, forKey: .targets)
        try c.encode(mode, forKey: .mode)
        try c.encode(base, forKey: .base)
        try c.encode(update, forKey: .update)
        try c.encode(keys, forKey: .keys)
        try c.encode(output, forKey: .output)
        try c.encode(exefs, forKey: .exefs)
        try c.encode(romfs, forKey: .romfs)
        try c.encode(aoc, forKey: .aoc)
        try c.encode(cache, forKey: .cache)
        try c.encode(library, forKey: .library)
        try c.encode(shaderAction, forKey: .shaderAction)
        try c.encode(jobs, forKey: .jobs)
        try c.encode(gamesIndex, forKey: .gamesIndex)
    }

    /// Indices the bridge needs for one platform of this batch. The task path and
    /// approval are added by the caller; nothing here guesses a default target.
    public func arguments(action: String, target: String? = nil) -> [String] {
        var result = [URL(fileURLWithPath: repository).appendingPathComponent("scripts/packaging_gui.py").path, action]
        let values: [(String, String)] = [
            ("target", target ?? targets.first ?? "macos"), ("mode", mode), ("base", base),
            ("update", update), ("keys", keys), ("output", output),
            ("exefs", exefs), ("romfs", romfs), ("aoc", aoc), ("cache", cache),
            ("library", library), ("shader-action", shaderAction), ("jobs", String(jobs))
        ]
        for (name, value) in values where !value.isEmpty && !(mode != "directory" && ["aoc", "romfs"].contains(name)) && !(automatic && ["exefs", "romfs", "cache", "shader-action"].contains(name)) { result += ["--" + name, value] }
        if automatic {
            result += ["--automatic", "1", "--cache-root", cache]
        }
        return result
    }

    public mutating func selectBase(_ value: String) {
        base = value
        if outputAutomatic { output = Self.suggestedOutput(forBase: value) }
    }

    public mutating func selectOutput(_ value: String) {
        output = value; outputAutomatic = false
    }

    public mutating func restoreOutput() {
        outputAutomatic = true; output = Self.suggestedOutput(forBase: base)
    }

    /// Override all saved developer paths when launched from a packaged App.
    public mutating func useBundle(_ resources: URL) {
        automatic = true
        repository = resources.appendingPathComponent("Packaging").path
        python = resources.appendingPathComponent("Python/bin/python3").path
        library = URL(fileURLWithPath: repository).appendingPathComponent("bin/nxrom.dylib").path
        gamesIndex = URL(fileURLWithPath: repository).appendingPathComponent("games.json").path
        exefs = ""; romfs = ""; shaderAction = "reuse"
        if cache.isEmpty { cache = Self.defaultCache }
    }

    public static var defaultCache: String {
        FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Caches/Touchline23Packaging").path
    }

    /// Bridge arguments for the supported-games list. Only the interpreter, the
    /// repository and an optional bundled catalog matter here: reading the list
    /// must not depend on a base game, keys or an output folder being selected.
    public func catalogArguments(index: String? = nil) -> [String] {
        var result = [URL(fileURLWithPath: repository).appendingPathComponent("scripts/packaging_gui.py").path, "games"]
        let chosen = index ?? gamesIndex
        if !chosen.isEmpty { result += ["--games-index", chosen] }
        return result
    }

    /// A selectable build capability. Only entries backed by a real, verified
    /// build path are offered; the rest stay visible but disabled so the window
    /// never claims support the engine does not have.
    public struct Option: Identifiable, Equatable, Sendable {
        public let id: String
        public let title: String
        public let supported: Bool
        public let note: String
        public init(id: String, title: String, supported: Bool, note: String) {
            self.id = id; self.title = title; self.supported = supported; self.note = note
        }
    }

    public static let targetOptions = [
        Option(id: "macos", title: "macOS App", supported: true, note: "Real build and artifact audit"),
        Option(id: "ios", title: "iOS IPA", supported: true, note: "Unsigned IPA and artifact audit"),
    ]
    public static let modeOptions = [
        Option(id: "nsp", title: "External XCI / NSP", supported: true, note: "Read base and optional NSP update; keep resources external"),
        Option(id: "directory", title: "Bundled resources (Directory)", supported: true, note: "Resources are prepared automatically"),
    ]

    public static func supportedTarget(_ id: String) -> Bool {
        targetOptions.first { $0.id == id }?.supported == true
    }

    /// Canonical order and no duplicates: a batch always builds macOS before iOS,
    /// whatever order the user picked them in.
    public static func normalized(_ values: [String]) -> [String] {
        let wanted = Set(values)
        return targetOptions.map(\.id).filter { wanted.contains($0) && supportedTarget($0) }
    }

    /// The platforms this batch will build, in execution order.
    public var orderedTargets: [String] { Configuration.normalized(targets) }

    public var capabilityIssue: String? {
        if orderedTargets.isEmpty { return "Select at least one target platform." }
        if !Configuration.modeOptions.contains(where: { $0.id == mode && $0.supported }) {
            return "This resource mode is unavailable."
        }
        return nil
    }

    public var launchIssue: String? {
        if let issue = capabilityIssue { return issue }
        if automatic && (!FileManager.default.isExecutableFile(atPath: python)
            || !FileManager.default.isReadableFile(atPath: URL(fileURLWithPath: repository).appendingPathComponent("release.json").path)) {
            return "Bundled runtime is missing. Rebuild or replace the App."
        }
        if python.isEmpty { return "Choose a project Python with capstone, lz4.block and fontTools." }
        if !FileManager.default.isExecutableFile(atPath: python) { return "Choose an executable Python interpreter." }
        let bridge = URL(fileURLWithPath: repository).appendingPathComponent("scripts/packaging_gui.py").path
        if !FileManager.default.isReadableFile(atPath: bridge) { return "Choose the GUI repository containing scripts/packaging_gui.py." }
        if !automatic && mode == "directory" && romfs.isEmpty { return "Directory mode requires an extracted RomFS folder." }
        if !aoc.isEmpty && !(orderedTargets == ["ios"] && mode == "directory") {
            return "DLC folders require iOS Directory mode; clear this input for other combinations."
        }
        return nil
    }

    /// A project virtual environment is only looked for inside the selected
    /// repository, so no absolute path of this or any other machine is assumed.
    /// Whether the result is usable is always decided by the dependency checks
    /// in a real review, never by this lookup.
    public static func discoveredPython(in repository: String) -> String? {
        guard !repository.isEmpty else { return nil }
        let root = URL(fileURLWithPath: repository)
        for relative in ["venv/bin/python3", ".venv/bin/python3", ".env/bin/python3"] {
            let candidate = root.appendingPathComponent(relative).path
            if FileManager.default.isExecutableFile(atPath: candidate) { return candidate }
        }
        return nil
    }

    public func redacted(_ text: String) -> String {
        var result = text
        for (value, label) in [(keys, "<key-file>"), (base, "<base-game>"), (update, "<update>"),
                               (aoc, "<dlc-folder>"),
                               (FileManager.default.homeDirectoryForCurrentUser.path, "<home>")]
            .filter({ !$0.0.isEmpty }).sorted(by: { $0.0.count > $1.0.count }) {
            result = result.replacingOccurrences(of: value, with: label)
        }
        return result.replacingOccurrences(of: #"(?<![0-9a-fA-F])[0-9a-fA-F]{32,64}(?![0-9a-fA-F])"#,
                                            with: "<redacted-digest-or-key>", options: .regularExpression)
    }

    public var privatePaths: [String] {
        [keys, base, update, aoc, exefs, cache, library,
         FileManager.default.homeDirectoryForCurrentUser.path].filter { !$0.isEmpty }
    }

    public var processEnvironment: [String: String] {
        var env = ProcessInfo.processInfo.environment.filter { ["USER", "LANG", "LC_ALL", "DOTNET_ROOT", "DOTNET_ROOT_ARM64"].contains($0.key) }
        env["PATH"] = [URL(fileURLWithPath: python).deletingLastPathComponent().path,
                       "/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"].joined(separator: ":")
        env["PYTHONDONTWRITEBYTECODE"] = "1"; env["PYTHONUNBUFFERED"] = "1"
        env["DOTNET_SKIP_FIRST_TIME_EXPERIENCE"] = "1"; env["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1"
        return env
    }

    /// The finished artifact is published next to the game file it was built
    /// from, so the folder containing the selected container is the natural
    /// default. This is only a suggestion: the review still rejects an output
    /// inside an input tree, inside the repository or inside the home folder.
    public static func suggestedOutput(forBase base: String) -> String {
        guard !base.isEmpty else { return "" }
        var directory: ObjCBool = false
        let isFolder = FileManager.default.fileExists(atPath: base, isDirectory: &directory) && directory.boolValue
        let folder = isFolder ? URL(fileURLWithPath: base) : URL(fileURLWithPath: base).deletingLastPathComponent()
        return folder.path == "/" ? "" : folder.path
    }

    public var recipeDisabledReason: String? {
        if shaderAction != "reuse" { return "Full Shader generation is available as a recipe preview only." }
        return nil
    }
}

public struct InterpreterIdentity: Codable, Sendable {
    public struct Dependency: Codable, Sendable {
        public var available: Bool
        public var version: String?
        public var distribution: String?
        public var reported: String? { version ?? distribution }
    }
    public var executable: String
    public var realpath: String
    public var version: String
    public var implementation: String
    public var dependencies: [String: Dependency]
    public var missing: [String]

    public var dependencySummary: String { dependencySummary(in: .english) }
    public func dependencySummary(in language: InterfaceLanguage) -> String {
        dependencies.keys.sorted().map { name in
            guard let state = dependencies[name], state.available else { return name + " " + GUIText(key: "missing").render(language) }
            return name + " " + (state.reported ?? GUIText(key: "version unknown").render(language))
        }.joined(separator: " · ")
    }
    public var summary: String { summary(in: .english) }
    public func summary(in language: InterfaceLanguage) -> String {
        "Python \(version) (\(implementation)) · " + dependencySummary(in: language)
    }

}

public struct IdentifiedGame: Codable, Equatable, Sendable {
    public var title_id: String
    /// The profile key, i.e. the base game Title ID the engine resolved.
    public var game: String?
    /// The profile's human label, as the confirmation sheet shows it.
    public var name: String?
}

public struct BuildReview: Codable, Sendable {
    public var prepared_shader: [String: String]? = nil
    public var execution_allowed: Bool
    public var disabled_reason: String
    public var fingerprint: String
    public var task_directory: String
    public var artifact_path: String
    public var git_sha: String
    /// Optional so a review written before interpreter identity existed still decodes.
    public var interpreter: InterpreterIdentity?
    /// The Title ID the resource itself reported, when the review could read it.
    public var identified: IdentifiedGame?
    /// The profile the engine resolved from that Title ID. Optional so a review
    /// written before the profile registry existed still decodes.
    public var game: String?
    public var game_name: String?
    public var inputs: [String: String]
    public var shader: [String: String]
    public var program_version: String
    public var shader_source_versions: [String]
    public var estimated_bytes: Int64
    public var free_bytes: Int64
    public var cleanup: String
    /// The stages this approved build will really run, in order. Optional so a
    /// review written before stage planning existed still decodes.
    public var stages: [BuildStage]?
    /// The platform and backend this review was made for. Optional for the same
    /// reason; the window always takes them from the configuration it checked.
    public var target: String? = nil
    public var mode: String? = nil
}
